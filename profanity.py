def find(text, extra=()):
    """اولین کلمه/عبارت توهین‌آمیز پیام، یا None.

    extra: کلمه‌هایی که ادمین خودش اضافه کرده (تطبیق کلمه‌ی کامل)."""
    t = _norm(text)
    if not t:
        return None
    # «f*ck»، «sh!t»: علامت وسط کلمه‌ی لاتین
    for raw in (text or "").lower().split():
        if raw.isascii():
            w = re.sub(r"[^a-z]", "", raw.translate(_LEET))
            if w and w in LATIN:
                return w
    toks = _join_spelled(t.split())
    padded = f" {' '.join(toks)} "
    for a in ALLOW_PHRASES:
        padded = padded.replace(f" {a} ", " ")
    toks = padded.split()
    for tok in toks:
        hit = _root_hit(tok)
        if hit:
            return hit
        if tok.isascii():
            lt = tok.translate(_LEET)
            if lt in LATIN or tok in LATIN:
                return tok
    for p in PHRASES:
        if f" {p} " in padded:
            return p
    for p in LATIN:
        if " " in p and f" {p} " in padded:
            return p
    for w in extra:
        w = _norm(w)
        if w and f" {w} " in padded:
            return w
    return None


def is_abusive(text, extra=()):
    return find(text, extra) is not None


