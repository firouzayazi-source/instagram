_AR = str.maketrans({"ي": "ی", "ى": "ی", "ك": "ک", "ة": "ه", "ۀ": "ه", "أ": "ا", "إ": "ا",
                     "ؤ": "و", "‌": " ", "‍": "", "ـ": ""})
_DIACRITICS = re.compile(r"[ً-ٰٟ]")
# هرچه حرف یا رقم نیست → فاصله (نقطه، ستاره، علامت، ایموجی)
_NON_WORD = re.compile(r"[^\w\s]|_", re.UNICODE)
_REPEAT = re.compile(r"(.)\1{2,}")
# فینگلیشِ رقمی: 3 = ع، 2 = ء — معمولاً بی‌ربط؛ فقط چند جایگزینی ایمن
_LEET = str.maketrans({"0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "@": "a", "$": "s", "!": "i"})


def _norm(text):
    t = (text or "").lower().translate(_AR)
    t = _DIACRITICS.sub("", t)
    t = _NON_WORD.sub(" ", t)
    t = _REPEAT.sub(r"\1", t)             # «کثافتتتت» → «کثافت»
    return " ".join(t.split())


def _join_spelled(tokens):
    """«ک ی ر» یا «ک.ث.ا.ف.ت» → «کیر»، «کثافت». فقط رشته‌ای از حروف تکی
    (حداقل سه‌تا) به هم چسبانده می‌شود؛ کلمه‌های عادی دست نمی‌خورند."""
    out, buf = [], []
    for t in tokens + [None]:
        if t is not None and len(t) == 1:
            buf.append(t); continue
        if len(buf) >= 3: out.append("".join(buf))
        else: out.extend(buf)
        buf = []
        if t is not None: out.append(t)
    return out


def _root_hit(tok):
    if tok in ALLOW:
        return None
    if tok in ROOTS or tok in EXACT:
        return tok
    for s in _SUFFIXES:
        if tok.endswith(s):
            base = tok[: -len(s)]
            if len(base) >= 3 and base in ROOTS:
                return base
    return None


